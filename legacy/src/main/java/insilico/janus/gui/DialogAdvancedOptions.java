    private void UpdateWorkflow() {
        Workflows = new HashMap<>();
        if (jCheckBox1.isSelected())
            Workflows.put(JanusEngine.WF_PERSISTENCE, true);
        if (jCheckBox2.isSelected())
            Workflows.put(JanusEngine.WF_BCF, true);
        if (jCheckBox3.isSelected())
            Workflows.put(JanusEngine.WF_TOXICITY, true);        
        if (jCheckBox4.isSelected())
            Workflows.put(JanusEngine.WF_CARCINOGENICITY, true);        
        if (jCheckBox5.isSelected())
            Workflows.put(JanusEngine.WF_MUTAGENICITY, true);        
        if (jCheckBox6.isSelected())
            Workflows.put(JanusEngine.WF_REPROTOX, true);        
        if (jCheckBox7.isSelected())
            Workflows.put(JanusEngine.WF_ED, true);        
    }
    
